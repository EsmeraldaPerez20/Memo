-- RF-20: al marcar un documento como eliminado se borran tambien sus fragmentos
-- (y, por cascada, las fuentes de mensajes que los citaban). El archivo del
-- almacenamiento privado lo borra el backend (Supabase Storage).
CREATE FUNCTION trg_documento_eliminado() RETURNS trigger AS $$
BEGIN
    IF NEW.fecha_eliminacion IS NOT NULL AND OLD.fecha_eliminacion IS NULL THEN
        DELETE FROM fragmentos WHERE documento_id = NEW.id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_documentos_eliminado AFTER UPDATE OF fecha_eliminacion ON documentos
    FOR EACH ROW EXECUTE FUNCTION trg_documento_eliminado();

