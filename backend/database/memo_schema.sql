    unidad_id     bigint       NOT NULL REFERENCES unidades(id) ON DELETE CASCADE,
    tema_padre_id bigint       REFERENCES temas(id) ON DELETE CASCADE,
    nombre        varchar(150) NOT NULL,
    descripcion   text,
    orden         smallint     NOT NULL DEFAULT 1
);
CREATE INDEX ix_temas_unidad ON temas (unidad_id);
CREATE INDEX ix_temas_padre  ON temas (tema_padre_id);


-- =====================================================================
--  3. DOCUMENTOS Y RAG  (Sprint 3: RF-13 a RF-20, RF-46, RF-47, RF-53, RNF-24)
-- =====================================================================

-- Apuntes privados del estudiante (RF-19)
CREATE TABLE documentos (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        bigint       NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    materia_id        bigint       REFERENCES materias(id) ON DELETE SET NULL,
    nombre            varchar(255) NOT NULL,
    archivo_url       varchar(500) NOT NULL,               -- ruta en Supabase Storage (bucket privado)
    tipo_archivo      varchar(10)  NOT NULL
                      CHECK (tipo_archivo IN ('pdf','docx','pptx','txt','png','jpg')),   -- RF-13
    tamano_bytes      bigint       NOT NULL
                      CHECK (tamano_bytes > 0 AND tamano_bytes <= 20971520),            -- RF-14: 20 MB
    estado_analisis   varchar(12)  NOT NULL DEFAULT 'pendiente'
                      CHECK (estado_analisis IN ('pendiente','procesando','completado','error')),
    fecha_analisis    timestamptz,
    fecha_subida      timestamptz  NOT NULL DEFAULT now(),
    fecha_eliminacion timestamptz                          -- borrado logico (RF-20)
);
CREATE INDEX ix_documentos_usuario ON documentos (usuario_id);

-- Materia/tema sugeridos por la IA y confirmados por el usuario (RF-18)
CREATE TABLE documento_temas (
    documento_id   bigint  NOT NULL REFERENCES documentos(id) ON DELETE CASCADE,
    tema_id        bigint  NOT NULL REFERENCES temas(id)      ON DELETE CASCADE,
    sugerido_por_ia boolean NOT NULL DEFAULT true,
    confirmado     boolean NOT NULL DEFAULT false,
    PRIMARY KEY (documento_id, tema_id)
);

-- Resultado del analisis automatico (RF-15, RF-16)
CREATE TABLE elementos_documento (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id   bigint       NOT NULL REFERENCES documentos(id) ON DELETE CASCADE,
    tipo           varchar(15)  NOT NULL
                   CHECK (tipo IN ('resumen','concepto','definicion','palabra_clave','pregunta','ejercicio','tema')),
    titulo         varchar(200),
    contenido      text         NOT NULL,
    fecha_creacion timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_elementos_documento ON elementos_documento (documento_id, tipo);

-- Materiales del docente, publicados solo tras aprobacion (RF-46, RF-47, RNF-24)
CREATE TABLE materiales (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id          bigint       NOT NULL REFERENCES materias(id) ON DELETE CASCADE,
    tema_id             bigint       REFERENCES temas(id) ON DELETE SET NULL,
    titulo              varchar(200) NOT NULL,
    descripcion         text,
    archivo_url         varchar(500) NOT NULL,
    tipo_archivo        varchar(10)  NOT NULL
                        CHECK (tipo_archivo IN ('pdf','docx','pptx','txt','png','jpg')),
    tamano_bytes        bigint       NOT NULL CHECK (tamano_bytes > 0 AND tamano_bytes <= 20971520),
    subido_por          bigint       NOT NULL REFERENCES usuarios(id),
    estado              varchar(20)  NOT NULL DEFAULT 'pendiente'
                        CHECK (estado IN ('pendiente','aprobado','rechazado')),
    revisado_por        bigint       REFERENCES usuarios(id),
    comentarios_revision text,
    fecha_revision      timestamptz,
    fecha_publicacion   timestamptz,
    fecha_subida        timestamptz  NOT NULL DEFAULT now(),
    -- Un material aprobado siempre debe tener quien lo reviso (RF-47)
    CHECK (estado <> 'aprobado' OR (revisado_por IS NOT NULL AND fecha_revision IS NOT NULL))
);
CREATE INDEX ix_materiales_materia ON materiales (materia_id, estado);

-- Trozos de texto con su embedding, para la busqueda semantica del RAG.
-- Cada fragmento viene de un documento privado O de un material (nunca de ambos).
-- Dimension 1536 = text-embedding-3-small de OpenAI; ajustar si se usa otro modelo.
CREATE TABLE fragmentos (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id   bigint REFERENCES documentos(id) ON DELETE CASCADE,
    material_id    bigint REFERENCES materiales(id) ON DELETE CASCADE,
    orden          integer NOT NULL,
    num_pagina     integer,
    contenido      text    NOT NULL,
    embedding      vector(1536),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    CHECK ((documento_id IS NOT NULL)::int + (material_id IS NOT NULL)::int = 1)
);
CREATE INDEX ix_fragmentos_documento ON fragmentos (documento_id);
CREATE INDEX ix_fragmentos_material  ON fragmentos (material_id);
CREATE INDEX ix_fragmentos_embedding ON fragmentos USING hnsw (embedding vector_cosine_ops);


-- =====================================================================
--  4. TUTORIA IA  (Sprint 3: RF-06 a RF-12, RF-52, RF-53, RNF-23)
-- =====================================================================

CREATE TABLE conversaciones (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id             bigint       NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    materia_id             bigint       REFERENCES materias(id)   ON DELETE SET NULL,
    documento_id           bigint       REFERENCES documentos(id) ON DELETE SET NULL,   -- RF-17
    titulo                 varchar(200),
    guardada               boolean      NOT NULL DEFAULT false,  -- consentimiento para conservar historial (RF-10, RF-11)
    fecha_inicio           timestamptz  NOT NULL DEFAULT now(),
    fecha_ultima_actividad timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_conversaciones_usuario ON conversaciones (usuario_id, fecha_ultima_actividad DESC);

CREATE TABLE mensajes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id bigint      NOT NULL REFERENCES conversaciones(id) ON DELETE CASCADE,
    emisor          varchar(10) NOT NULL CHECK (emisor IN ('estudiante','ia')),
    contenido       text        NOT NULL,
    modo_explicacion varchar(15) NOT NULL DEFAULT 'normal'
                    CHECK (modo_explicacion IN ('normal','sencilla','detallada','otro_ejemplo')),  -- RF-09
    advertencia_ia  boolean     NOT NULL DEFAULT false,   -- IA sin info suficiente o con duda (RF-12, RNF-23)
    fecha_envio     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_mensajes_conversacion ON mensajes (conversacion_id, fecha_envio);

-- Cada mensaje de la IA con las fuentes que uso (RF-53)
CREATE TABLE mensaje_fuentes (
    mensaje_id  bigint NOT NULL REFERENCES mensajes(id)   ON DELETE CASCADE,
    fragmento_id bigint NOT NULL REFERENCES fragmentos(id) ON DELETE CASCADE,
    relevancia  numeric(5,4) CHECK (relevancia BETWEEN 0 AND 1),
    PRIMARY KEY (mensaje_id, fragmento_id)
);

-- Reporte de respuestas incorrectas de la IA (RF-52)
CREATE TABLE reportes_ia (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id      bigint      REFERENCES mensajes(id) ON DELETE SET NULL,   -- queda NULL si se elimina la conversacion (RF-11)
    contenido_reportado text    NOT NULL,                -- copia del mensaje reportado: el reporte no se pierde (RF-11, RF-52)
    usuario_id      bigint      NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    motivo          varchar(15) NOT NULL CHECK (motivo IN ('incorrecta','incompleta','inapropiada','otro')),
    comentario      text,
    estado          varchar(10) NOT NULL DEFAULT 'abierto' CHECK (estado IN ('abierto','revisado','descartado')),
    revisado_por    bigint REFERENCES usuarios(id) ON DELETE SET NULL,
    fecha_reporte   timestamptz NOT NULL DEFAULT now(),
    fecha_revision  timestamptz
);
CREATE INDEX ix_reportes_ia_estado ON reportes_ia (estado);

-- La conversacion se "mueve" cada vez que llega un mensaje nuevo
CREATE FUNCTION trg_conversacion_actividad() RETURNS trigger AS $$
BEGIN
    UPDATE conversaciones SET fecha_ultima_actividad = now() WHERE id = NEW.conversacion_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_mensajes_actividad AFTER INSERT ON mensajes
    FOR EACH ROW EXECUTE FUNCTION trg_conversacion_actividad();


