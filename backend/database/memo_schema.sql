CREATE TABLE roles (
    id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      varchar(30)  NOT NULL UNIQUE,          -- estudiante | docente | administrador (RF-03)
    descripcion varchar(200)
);

-- Permisos granulares para el control de acceso por roles (RF-49, RNF-03)
CREATE TABLE permisos (
    id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      varchar(60)  NOT NULL UNIQUE,          -- ej. 'materiales.aprobar'
    descripcion varchar(200)
);

CREATE TABLE roles_permisos (
    rol_id     smallint NOT NULL REFERENCES roles(id)    ON DELETE CASCADE,
    permiso_id smallint NOT NULL REFERENCES permisos(id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE usuarios (
    id                           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id                       smallint     NOT NULL REFERENCES roles(id),
    nombre                       varchar(100) NOT NULL,
    apellido                     varchar(100),                 -- opcional: el registro solo exige nombre (RF-01)
    correo                       varchar(150) NOT NULL,
    password_hash                varchar(255),                 -- nunca texto plano (RNF-04); NULL en cuentas creadas con Google
    activo                       boolean      NOT NULL DEFAULT true,
    google_id                    varchar(100) UNIQUE,          -- "sub" de la cuenta de Google; NULL si no usa Google
    telefono                     varchar(20)  CHECK (telefono ~ '^\+[1-9][0-9]{7,14}$'),   -- formato internacional (+52...), para WhatsApp
    aviso_privacidad_version     varchar(20),                  -- RNF-05
    aviso_privacidad_aceptado_en timestamptz,
    ultimo_acceso                timestamptz,
    fecha_registro               timestamptz  NOT NULL DEFAULT now(),
    fecha_actualizacion          timestamptz  NOT NULL DEFAULT now()
);
-- Correo unico sin importar mayusculas/minusculas (RF-01, RF-02)
CREATE UNIQUE INDEX ux_usuarios_correo ON usuarios (lower(correo));
CREATE INDEX ix_usuarios_rol ON usuarios (rol_id);

-- Perfil academico: solo estudiantes (RF-01, RF-05)
CREATE TABLE perfiles_academicos (
    usuario_id          bigint PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
    carrera             varchar(150),
    semestre            smallint CHECK (semestre BETWEEN 1 AND 15),
    institucion         varchar(200) DEFAULT 'Universidad Politécnica de Tlaxcala Región Poniente',
    nivel_academico     varchar(15)  NOT NULL DEFAULT 'basico'
                        CHECK (nivel_academico IN ('basico','intermedio','avanzado')),   -- RF-08
    fecha_actualizacion timestamptz  NOT NULL DEFAULT now()
);

-- Recuperacion de contrasena por correo (RF-04)
CREATE TABLE tokens_recuperacion (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     bigint       NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token_hash     varchar(255) NOT NULL,           -- se guarda el hash, no el token
    expira_en      timestamptz  NOT NULL,
    usado          boolean      NOT NULL DEFAULT false,
    fecha_creacion timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_tokens_recuperacion_usuario ON tokens_recuperacion (usuario_id);

-- Accesibilidad (RNF-19) y notificaciones configurables (RF-54)
CREATE TABLE preferencias_usuario (
    usuario_id              bigint PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
    modo_oscuro             boolean  NOT NULL DEFAULT false,
    tamano_letra            smallint NOT NULL DEFAULT 16 CHECK (tamano_letra BETWEEN 12 AND 32),
    lectura_texto           boolean  NOT NULL DEFAULT false,
    alto_contraste          boolean  NOT NULL DEFAULT false,
    notif_recomendaciones   boolean  NOT NULL DEFAULT true,
    notif_recordatorios     boolean  NOT NULL DEFAULT true,
    notif_resultados        boolean  NOT NULL DEFAULT true,
    notif_materiales        boolean  NOT NULL DEFAULT true,
    notif_avances           boolean  NOT NULL DEFAULT true,
    canal_app               boolean  NOT NULL DEFAULT true,
    canal_correo            boolean  NOT NULL DEFAULT false,
    canal_whatsapp          boolean  NOT NULL DEFAULT false,
    fecha_actualizacion     timestamptz NOT NULL DEFAULT now()
);


