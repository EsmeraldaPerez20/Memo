    fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
    fecha_superacion    timestamptz
);
-- Solo una dificultad activa por estudiante y tema
CREATE UNIQUE INDEX ux_dificultad_activa ON dificultades (usuario_id, tema_id) WHERE estado = 'activa';

-- Respuestas que originaron la dificultad: la "evidencia" (RF-24)
CREATE TABLE dificultad_evidencias (
    dificultad_id bigint NOT NULL REFERENCES dificultades(id) ON DELETE CASCADE,
    respuesta_id  bigint NOT NULL REFERENCES respuestas(id)   ON DELETE CASCADE,
    PRIMARY KEY (dificultad_id, respuesta_id)
);


