CREATE TABLE materias (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         varchar(100) NOT NULL,
    descripcion    text,
    activa         boolean      NOT NULL DEFAULT true,
    creada_por     bigint REFERENCES usuarios(id) ON DELETE SET NULL,
    fecha_creacion timestamptz  NOT NULL DEFAULT now()
);

-- Una persona cursa (estudiante) o imparte (docente) una materia
CREATE TABLE usuarios_materias (
    usuario_id bigint      NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    materia_id bigint      NOT NULL REFERENCES materias(id) ON DELETE CASCADE,
