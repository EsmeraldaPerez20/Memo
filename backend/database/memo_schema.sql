    tema_id               bigint       NOT NULL REFERENCES temas(id)    ON DELETE CASCADE,
    porcentaje            numeric(5,2) NOT NULL DEFAULT 0 CHECK (porcentaje BETWEEN 0 AND 100),
    probabilidad_dominio  numeric(5,4) CHECK (probabilidad_dominio BETWEEN 0 AND 1),  -- salida del Knowledge Tracing
    nivel_dominio         varchar(15)  NOT NULL DEFAULT 'no_iniciado'
                          CHECK (nivel_dominio IN ('no_iniciado','bajo','medio','alto','dominado')),
    intentos_totales      integer      NOT NULL DEFAULT 0,
    aciertos              integer      NOT NULL DEFAULT 0,
    errores               integer      NOT NULL DEFAULT 0,
    tiempo_total_segundos bigint       NOT NULL DEFAULT 0,
    fecha_actualizacion   timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (usuario_id, tema_id)
);

-- Dificultades detectadas (RF-21, RF-22, RF-23)
CREATE TABLE dificultades (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          bigint      NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    tema_id             bigint      NOT NULL REFERENCES temas(id)    ON DELETE CASCADE,
    nivel               varchar(10) NOT NULL CHECK (nivel IN ('baja','media','alta')),   -- RF-23
    estado              varchar(10) NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa','superada')),
    errores_relevantes  smallint    NOT NULL DEFAULT 0,
    alerta_generada     boolean     NOT NULL DEFAULT false,   -- se activa al llegar a 3 errores (RF-22)
