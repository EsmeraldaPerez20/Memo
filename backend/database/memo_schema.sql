-- Banco de preguntas reutilizable; las variaciones apuntan a su pregunta base (RF-35)
CREATE TABLE banco_preguntas (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tema_id            bigint      NOT NULL REFERENCES temas(id) ON DELETE CASCADE,
    documento_id       bigint      REFERENCES documentos(id) ON DELETE SET NULL,
    pregunta_base_id   bigint      REFERENCES banco_preguntas(id) ON DELETE SET NULL,
    tipo               varchar(20) NOT NULL
                       CHECK (tipo IN ('opcion_multiple','verdadero_falso','relacion_columnas',
                                       'completar_espacios','abierta','problema_matematico','practico')),   -- RF-27
    enunciado          text        NOT NULL,
    opciones           jsonb,                       -- lista de opciones o pares a relacionar
    respuesta_correcta text        NOT NULL,        -- para relacion de columnas se guarda como JSON
    explicacion        text,
    dificultad         varchar(10) NOT NULL CHECK (dificultad IN ('baja','media','alta')),
    origen             varchar(10) NOT NULL DEFAULT 'ia' CHECK (origen IN ('ia','docente')),
    validada           boolean     NOT NULL DEFAULT false,   -- revision docente (RNF-21, RNF-24)
    fecha_creacion     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_banco_preguntas_tema ON banco_preguntas (tema_id, dificultad);

-- Ejercicio, quiz, simulacro o examen generado (RF-26, RF-32, RF-35)
CREATE TABLE actividades (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        bigint       NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,  -- quien la genero
    materia_id        bigint       NOT NULL REFERENCES materias(id),
    tipo              varchar(10)  NOT NULL CHECK (tipo IN ('ejercicio','quiz','simulacro','examen')),
    titulo            varchar(200) NOT NULL,
    dificultad        varchar(10)  NOT NULL CHECK (dificultad IN ('baja','media','alta','adaptativa')),  -- RF-28, RF-29
    num_preguntas     smallint     NOT NULL CHECK (num_preguntas > 0),
    limite_tiempo_min smallint     CHECK (limite_tiempo_min > 0),   -- NULL = sin limite (RF-34)
    generada_por      varchar(10)  NOT NULL DEFAULT 'ia' CHECK (generada_por IN ('ia','docente')),
    fecha_creacion    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_actividades_usuario ON actividades (usuario_id, fecha_creacion DESC);

CREATE TABLE actividad_temas (
    actividad_id bigint NOT NULL REFERENCES actividades(id) ON DELETE CASCADE,
    tema_id      bigint NOT NULL REFERENCES temas(id)       ON DELETE CASCADE,
    PRIMARY KEY (actividad_id, tema_id)
);

CREATE TABLE actividad_preguntas (
    actividad_id bigint   NOT NULL REFERENCES actividades(id)     ON DELETE CASCADE,
    pregunta_id  bigint   NOT NULL REFERENCES banco_preguntas(id) ON DELETE CASCADE,
    orden        smallint NOT NULL DEFAULT 1,
    PRIMARY KEY (actividad_id, pregunta_id)
);

-- Cada vez que el estudiante resuelve una actividad (RF-31, RF-33, RF-36)
CREATE TABLE intentos (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id      bigint      NOT NULL REFERENCES actividades(id) ON DELETE CASCADE,
    usuario_id        bigint      NOT NULL REFERENCES usuarios(id)    ON DELETE CASCADE,
    numero_intento    smallint    NOT NULL DEFAULT 1,
    estado            varchar(12) NOT NULL DEFAULT 'en_curso'
                      CHECK (estado IN ('en_curso','finalizado','expirado')),
    calificacion      numeric(5,2) CHECK (calificacion BETWEEN 0 AND 100),
    tiempo_segundos   integer,
    retroalimentacion text,
    fecha_inicio      timestamptz NOT NULL DEFAULT now(),
    fecha_fin         timestamptz,
    UNIQUE (actividad_id, usuario_id, numero_intento)
);
CREATE INDEX ix_intentos_usuario ON intentos (usuario_id, fecha_inicio DESC);

CREATE TABLE respuestas (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intento_id        bigint      NOT NULL REFERENCES intentos(id)        ON DELETE CASCADE,
    pregunta_id       bigint      NOT NULL REFERENCES banco_preguntas(id) ON DELETE CASCADE,
    respuesta_usuario text,
    es_correcta       boolean,                       -- NULL = pendiente de calificar (preguntas abiertas)
    puntaje           numeric(5,2),
    retroalimentacion text,                          -- explicacion del error (RF-30)
    tiempo_segundos   integer,
    fecha_respuesta   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (intento_id, pregunta_id)
);
CREATE INDEX ix_respuestas_pregunta ON respuestas (pregunta_id);


