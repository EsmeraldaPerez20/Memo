-- =====================================================================
--  SEGURIDAD (importante en Supabase)
--  Supabase expone por API REST las tablas del esquema public que no tengan
--  RLS activado, y aqui viven los password_hash. Con RLS activado y sin
--  politicas, la API publica no ve nada; el backend (Django) se conecta con
--  el usuario "postgres" y no se ve afectado. (RNF-01, RNF-02)
-- =====================================================================
DO $$
DECLARE t record;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t.tablename);
    END LOOP;
END $$;


