-- Indicadores generales de cada estudiante
CREATE VIEW v_dashboard_estudiante AS
SELECT
    u.id AS usuario_id,
    (SELECT COUNT(*) FROM progreso p
      WHERE p.usuario_id = u.id AND p.nivel_dominio IN ('alto','dominado'))           AS temas_dominados,
    (SELECT COUNT(*) FROM dificultades d
      WHERE d.usuario_id = u.id AND d.estado = 'activa')                              AS dificultades_activas,
    (SELECT ROUND(AVG(i.calificacion), 2) FROM intentos i
      WHERE i.usuario_id = u.id AND i.estado = 'finalizado')                          AS promedio_calificacion,
    (SELECT COUNT(*) FROM intentos i
      WHERE i.usuario_id = u.id AND i.estado = 'finalizado')                          AS actividades_realizadas,
    (SELECT COALESCE(SUM(i.tiempo_segundos), 0) FROM intentos i
      WHERE i.usuario_id = u.id)                                                      AS tiempo_total_segundos,
    (SELECT COUNT(*) FROM tareas t
      WHERE t.usuario_id = u.id AND NOT t.completada)                                 AS tareas_pendientes
FROM usuarios u
JOIN roles r ON r.id = u.rol_id
WHERE r.nombre = 'estudiante';

-- Avance de cada estudiante por materia
CREATE VIEW v_progreso_por_materia AS
SELECT
    p.usuario_id,
    m.id     AS materia_id,
    m.nombre AS materia,
    ROUND(AVG(p.porcentaje), 2) AS porcentaje_promedio,
    COUNT(*) FILTER (WHERE p.nivel_dominio IN ('alto','dominado')) AS temas_dominados,
    COUNT(*) AS temas_con_actividad
FROM progreso p
JOIN temas t     ON t.id  = p.tema_id
JOIN unidades un ON un.id = t.unidad_id
JOIN materias m  ON m.id  = un.materia_id
GROUP BY p.usuario_id, m.id, m.nombre;


